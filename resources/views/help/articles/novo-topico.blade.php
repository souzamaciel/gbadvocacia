<p>Cole o texto de uma petição já pronta e transforme-o em modelo. A IA sugere o que deve virar campo a completar, o título e o grupo.</p>
<h4>Etapa 1 · Colar o texto</h4>
<x-help-figure src="novo-topico-1" caption="Cole o texto no editor. A formatação é mantida até o Word." />
<ol>
    <li>Na Biblioteca, clique em <strong>Novo tópico</strong> e cole o texto. Título e grupo podem ficar em branco por enquanto.</li>
    <li>Clique em <strong>Identificar variáveis com IA</strong>, ou selecione um trecho e use <strong>Criar variável manualmente</strong>.</li>
</ol>
<h4>Etapa 2 · Revisar variáveis</h4>
<x-help-figure src="novo-topico-2" caption="Cada sugestão aparece numerada no texto e na lista à direita." />
<ol start="3">
    <li>Para cada sugestão, ajuste o nome se quiser e clique em <strong>Aceitar</strong> (vira campo) ou <strong>Manter original</strong> (fica como texto fixo).</li>
    <li>Sugestões com <strong>atenção</strong> podem ser comuns a vários clientes: confira com cuidado.</li>
    <li>Quando todas forem revisadas, clique em <strong>Continuar</strong>.</li>
</ol>
<x-help-figure src="novo-topico-2b" caption="Tudo revisado: os trechos aceitos ficam em verde." />
<h4>Etapa 3 · Salvar modelo</h4>
<x-help-figure src="novo-topico-3" caption="Título e grupo sugeridos pela IA. A orientação interna é opcional." />
<ol start="6">
    <li>Confira o <strong>título</strong> e o <strong>grupo</strong>, escreva a <strong>orientação interna</strong> se quiser e clique em <strong>Salvar tópico</strong>.</li>
</ol>
<div class="gb-help-note"><i data-lucide="coins"></i><div>Cada uso de “Identificar variáveis com IA” consulta a OpenAI e gera um pequeno custo.</div></div>

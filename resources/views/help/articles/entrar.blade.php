<h4>Primeiro acesso: troca obrigatória da senha</h4>
<p>Quando o administrador cadastra você ou redefine sua senha, ele informa uma <strong>senha provisória</strong>. Ao entrar com ela, o sistema abre <strong>Meu perfil</strong> e só libera as outras telas depois que você cria a sua própria senha.</p>

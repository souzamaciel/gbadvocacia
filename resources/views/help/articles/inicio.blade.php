<h4>No celular</h4>
<p>O sistema funciona no celular e no tablet. O menu fica no botão <strong>☰</strong>, no canto superior direito, e ali também estão a Base de conhecimento e o Sugerir melhoria. Para montar e revisar petições, prefira o computador.</p>

<p>A tela <strong>Logs de atividade</strong> mostra quem fez o quê no sistema, quando e de onde. Ela aparece só para o superadmin, no menu do seu nome.</p>
<h4>O que é registrado</h4>
<ul>
    <li><strong>Acesso:</strong> entradas, tentativas com senha errada, saídas e mudanças no próprio perfil.</li>
    <li><strong>Atendimentos e petições:</strong> criar, salvar, concluir, importar, imprimir, gerar o Word e excluir.</li>
    <li><strong>Usuários e perfis:</strong> cadastro, alteração, senha provisória, ativação e desativação.</li>
    <li><strong>Biblioteca e ficha:</strong> tópicos, grupos e mudanças na ficha de atendimento.</li>
    <li><strong>Sugestões:</strong> cada sugestão enviada pela equipe.</li>
</ul>
<h4>Como ler cada linha</h4>
<p>Cada registro traz data e hora, o usuário, a ação (com o cliente ou o item envolvido) e a origem: IP, cidade aproximada, navegador, sistema e tipo de aparelho.</p>
<p>Use os filtros de período, usuário, área e a busca (por cliente, usuário, IP ou cidade) para encontrar o que precisa.</p>
<div class="gb-help-note"><i data-lucide="map-pin"></i><div>A localização é <strong>aproximada</strong>, calculada pelo IP da internet (do provedor). Os computadores de uma mesma rede aparecem com o mesmo IP.</div></div>
<div class="gb-help-note is-warning"><i data-lucide="clock"></i><div>Os registros ficam guardados por <strong>6 meses</strong> e depois são apagados automaticamente.</div></div>

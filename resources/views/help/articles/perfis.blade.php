<x-help-figure src="editar-perfil" caption="Marque as permissões. As mudanças valem na hora para todos que usam o perfil." />
<ul>
    <li><strong>Novo perfil</strong> cria um perfil do zero; o ícone <strong>copiar</strong> duplica um existente.</li>
    <li>Algumas permissões dependem de outras e são marcadas juntas (ex.: “Usar a IA” marca “Criar e editar tópicos”).</li>
    <li>O perfil <strong>Administrador</strong> é fixo e tem sempre todas as permissões. Só é possível excluir um perfil que ninguém usa.</li>
</ul>

<ul>
    <li>Filtre por <strong>Ativos</strong> e <strong>Desativados</strong> e busque por nome ou e-mail.</li>
    <li>A etiqueta <strong>Senha provisória</strong> indica quem ainda não criou a própria senha.</li>
</ul>
<h4>Cadastrar</h4>
<x-help-figure src="novo-usuario" caption="Ao escolher o perfil, o quadro à direita mostra o que ele permite." />
<ol>
    <li>Clique em <strong>Novo usuário</strong> e preencha nome, e-mail e perfil.</li>
    <li>Crie a senha provisória ou clique em <strong>Gerar</strong>.</li>
    <li>Clique em <strong>Cadastrar usuário</strong> e informe o e-mail e a senha à pessoa. No primeiro acesso, ela cria a própria senha.</li>
</ol>
<h4>Editar, redefinir senha e desativar</h4>
<x-help-figure src="editar-usuario" caption="Dados, perfil e “Redefinir senha” na mesma tela." />
<ul>
    <li><strong>Redefinir senha:</strong> defina uma nova senha provisória; a troca será pedida no próximo acesso.</li>
    <li><strong>Desativar:</strong> a pessoa deixa de entrar na hora. As petições e atendimentos feitos por ela continuam salvos. Você pode reativar quando quiser.</li>
</ul>
<div class="gb-help-note is-warning"><i data-lucide="shield-alert"></i><div>Ninguém pode desativar a si mesmo nem mudar o próprio perfil, e o sistema sempre mantém pelo menos um administrador ativo. Usuários não são excluídos, só desativados.</div></div>

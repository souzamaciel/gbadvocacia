<h4>Esqueci minha senha. O que faço?</h4>
<p>Peça ao administrador para redefinir a senha em Usuários. Você receberá uma senha provisória e criará a sua no primeiro acesso.</p>
<h4>Perdi o Word da petição. Consigo recuperar?</h4>
<p>Sim. Abra o rascunho (em Petições ou Atendimentos) e gere novamente. Os rascunhos ficam salvos com todas as respostas e revisões.</p>
<h4>Editei um texto na revisão. O modelo da Biblioteca muda?</h4>
<p>Não. Os ajustes na revisão valem só para aquela petição. Para mudar o modelo, edite o tópico na Biblioteca.</p>
<h4>O que é a faixa verde “Orientação interna” no Word?</h4>
<p>É a instrução do escritório para aquele tópico. <strong>Apague esses trechos antes de protocolar.</strong></p>
<h4>Por que um botão está cinza?</h4>
<p>Porque ainda falta algo para a ação ser possível. A mensagem ao lado diz o que preencher.</p>
<h4>Não vejo um menu que um colega vê.</h4>
<p>Cada um vê apenas o que o seu perfil permite. Confira em <strong>Meu perfil → Seu acesso</strong> e fale com o administrador se precisar de mais acesso.</p>
<h4>A ficha mudou. Os rascunhos antigos continuam valendo?</h4>
<p>Sim. As respostas das perguntas que continuam na ficha são mantidas; perguntas removidas deixam de aparecer.</p>
<h4>Um colega saiu do escritório. Devo excluir o usuário?</h4>
<p>Use <strong>Desativar</strong>: ele perde o acesso na hora, e o que ele fez continua no sistema com o nome do autor.</p>
